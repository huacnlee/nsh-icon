#!/usr/bin/env bun
// Sync the pinned Lucide release (lucide.json) into icons/: every canonical
// SVG byte for byte, the deprecated aliases (icons/aliases.txt) and the
// upstream license (LICENSE-LUCIDE). --check verifies without writing.
// --archive reads a local copy of the upstream tarball instead of downloading.
//
// After a sync, regenerate the TSX constants:
//   NSH_LUCIDE_UPDATE=1 cargo test --test tsx
import { readdir, rm } from "node:fs/promises";
import { resolve } from "node:path";
import { parseArgs } from "node:util";

async function main() {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: {
      check: { type: "boolean", default: false },
      archive: { type: "string" },
      help: { type: "boolean", short: "h" },
    },
    strict: true,
    allowPositionals: false,
  });
  if (values.help) {
    console.log("Usage: bun script/sync-lucide.ts [--check] [--archive archive.tar.gz]");
    return;
  }

  const root = resolve(import.meta.dir, "..");
  const manifest: { version: string; archive_url: string; sha256: string; icon_count: number } =
    await Bun.file(resolve(root, "lucide.json")).json();

  let data: Uint8Array;
  if (values.archive) {
    data = await Bun.file(values.archive).bytes();
  } else {
    const response = await fetch(manifest.archive_url, { signal: AbortSignal.timeout(60_000) });
    if (!response.ok) throw new Error(`Lucide download failed: HTTP ${response.status}`);
    data = new Uint8Array(await response.arrayBuffer());
  }
  if (new Bun.CryptoHasher("sha256").update(data).digest("hex") !== manifest.sha256) {
    throw new Error("Lucide archive checksum mismatch");
  }

  const files = new Map<string, Buffer>();
  const aliases: string[] = [];
  for (const [name, file] of await new Bun.Archive(data).files()) {
    const parts = name.split("/");
    if (parts.length === 3 && parts[1] === "icons" && parts[2].endsWith(".svg")) {
      files.set(`icons/${parts[2]}`, Buffer.from(await file.arrayBuffer()));
    } else if (parts.length === 3 && parts[1] === "icons" && parts[2].endsWith(".json")) {
      const icon = parts[2].slice(0, -".json".length);
      const meta = JSON.parse(await file.text());
      for (const alias of meta.aliases ?? []) {
        const aliasName = typeof alias === "string" ? alias : alias.name;
        aliases.push(`${aliasName} ${icon}`);
      }
    } else if (parts.length === 2 && parts[1] === "LICENSE") {
      files.set("LICENSE-LUCIDE", Buffer.from(await file.arrayBuffer()));
    }
  }
  const icons = [...files.keys()].filter((name) => name.startsWith("icons/"));
  if (!files.has("LICENSE-LUCIDE") || icons.length !== manifest.icon_count) {
    throw new Error(`Unexpected Lucide archive layout or icon count (${icons.length})`);
  }
  aliases.sort();
  files.set(
    "icons/aliases.txt",
    Buffer.from(
      `# Deprecated Lucide ${manifest.version} names: <alias> <icon>. Generated by script/sync-lucide.ts.\n` +
        aliases.map((line) => `${line}\n`).join(""),
    ),
  );

  let changed = 0;
  for (const [name, content] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    const target = Bun.file(resolve(root, name));
    if (!(await target.exists()) || !content.equals(Buffer.from(await target.arrayBuffer()))) {
      changed++;
      if (!values.check) await Bun.write(target, content);
    }
  }
  // Icons a release removed or renamed leave the catalog.
  for (const entry of await readdir(resolve(root, "icons"))) {
    if (!files.has(`icons/${entry}`)) {
      changed++;
      if (!values.check) await rm(resolve(root, "icons", entry));
    }
  }
  if (values.check && changed) {
    throw new Error(`${changed} Lucide files missing or out of date; run bun script/sync-lucide.ts`);
  }
  console.log(
    `Lucide ${manifest.version}: ${icons.length} icons, ${aliases.length} aliases; ${changed} files ${values.check ? "differ" : "updated"}`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
